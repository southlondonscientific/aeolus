def test_fixture_provenance_is_documented():
    """A provenance file must exist alongside the data fixtures so readers
    can see which openair version produced them."""
    provenance_path = FIXTURES / "provenance.csv"
    assert provenance_path.exists(), (
        "Missing provenance.csv — regenerate fixtures with "
        "scripts/validation/generate_openair_fixtures.R"
    )
    prov = pd.read_csv(provenance_path)
    assert "openair_version" in prov.columns
    assert not prov.empty
