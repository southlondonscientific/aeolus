"""Numerical parity tests against R openair.

These tests assert that aeolus metrics produce numerically identical output
to R openair for the same input. Reference outputs are pre-generated by
``scripts/validation/generate_openair_fixtures.R`` and checked into
``tests/fixtures/openair/``. You do not need R installed to run these tests.

The comparison pattern is deliberately conservative:
1. Load raw AURN data that openair produced (same bytes, same upstream source)
2. Convert that raw wide-format DataFrame to the aeolus long-format schema
3. Run the aeolus metric
4. Reshape aeolus output back to wide format
5. Assert value-by-value equivalence to the openair reference

This isolates metric-computation parity from data-loading differences. If
aeolus.download() and openair.importAURN() produced different raw data, that
would be a separate (and legitimate) bug — but it's not what this test file
is checking.

See ``docs/validation/openair-parity.qmd`` for the user-facing narrative
comparison rendered from this same fixture data.
"""

