def _pivot_aeolus_to_wide(df: pd.DataFrame) -> pd.DataFrame:
    """Reshape aeolus long-format output into openair-style wide format."""
    wide = df.pivot_table(
        index="date_time",
        columns="measurand",
        values="value",
        aggfunc="first",  # after time_average there's one value per cell
    )
    wide = wide.reset_index().rename(columns={"date_time": "date"})
    # Map aeolus measurand names back to openair's lowercase form
    rename = {"NO2": "no2", "PM2.5": "pm2.5", "PM10": "pm10", "O3": "o3"}
    wide = wide.rename(columns=rename)
    return wide


def _assert_wide_frames_match(
    aeolus_wide: pd.DataFrame,
    openair_wide: pd.DataFrame,
    pollutants: list[str],
    atol: float = 1e-12,
) -> None:
    """Tolerance is set at 1e-12 ug/m3 — eight orders of magnitude below any
    physically meaningful measurement. Observed max diff is ~5e-14, so this
    leaves margin for floating-point order-of-operations drift but would
    catch any real algorithmic divergence."""
    """Compare wide-format DataFrames, aligned on date. Fail with a diff table."""
    # Align on date
    merged = aeolus_wide.merge(
        openair_wide, on="date", how="outer", suffixes=("_aeolus", "_openair")
    )

    for p in pollutants:
        a_col = f"{p}_aeolus"
        o_col = f"{p}_openair"
        if a_col not in merged.columns or o_col not in merged.columns:
            pytest.fail(f"Missing comparison column for {p}: {a_col}/{o_col}")

        a = merged[a_col].to_numpy()
        o = merged[o_col].to_numpy()

        # Both NaN in the same places — openair and aeolus agree on coverage
        a_nan = np.isnan(a)
        o_nan = np.isnan(o)
        nan_mismatch = (a_nan != o_nan).sum()
        assert nan_mismatch == 0, (
            f"{p}: {nan_mismatch} rows have NaN in one frame but not the other. "
            f"Likely a data-capture threshold mismatch."
        )

        # Compare non-NaN values
        both_valid = ~a_nan & ~o_nan
        diffs = np.abs(a[both_valid] - o[both_valid])
        max_diff = diffs.max() if len(diffs) else 0.0
        n_beyond_tol = (diffs > atol).sum()

        assert n_beyond_tol == 0, (
            f"{p}: {n_beyond_tol}/{both_valid.sum()} rows differ by more "
            f"than {atol} ug/m3. Max diff: {max_diff:g}."
        )


class TestTimeAverageDailyMean:
    """aeolus.time_average(freq='D', data_thresh=0.75) must match
    openair::timeAverage(avg.time='day', data.thresh=75)."""

    def test_daily_mean_matches_openair(self, raw_long, openair_daily_mean):
        aeolus_daily = time_average(raw_long, freq="D", data_thresh=0.75)
        aeolus_wide = _pivot_aeolus_to_wide(aeolus_daily)
        _assert_wide_frames_match(
            aeolus_wide,
            openair_daily_mean,
            pollutants=["no2", "pm2.5", "pm10", "o3"],
        )

    def test_row_count_matches(self, raw_long, openair_daily_mean):
        """Both should emit one row per day regardless of data capture — a
        day below threshold becomes NaN, not absent."""
        aeolus_daily = time_average(raw_long, freq="D", data_thresh=0.75)
        unique_days = aeolus_daily["date_time"].dt.normalize().nunique()
        assert unique_days == len(openair_daily_mean), (
            f"aeolus produced {unique_days} days, openair produced "
            f"{len(openair_daily_mean)}"
        )


